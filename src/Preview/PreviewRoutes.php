declare(strict_types=1);

namespace Blush\Preview;

use Override;
use Blush\Routing\Route;
use Blush\Routing\RoutePriority;
use Blush\Routing\RouteSource;

/**
 * The preview route, only while preview links are on (a secret is set).
 */
final readonly class PreviewRoutes implements RouteSource
{
	public function __construct(private PreviewConfig $config)
	{}

	/**
	 * @inheritDoc
	 */
	#[Override]
	public function priority(): RoutePriority
	{
		return RoutePriority::System;
	}

	/**
	 * @inheritDoc
	 * @return list<Route>
	 */
	#[Override]
	public function routes(): iterable
	{
		return $this->config->isEnabled()
			? [Route::get($this->config->path, PreviewController::class)->named('preview')->exact()]
			: [];
	}
}
